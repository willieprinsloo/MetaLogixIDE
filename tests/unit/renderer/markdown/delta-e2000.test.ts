const round4 = (x: number) => Math.round(x * 1e4) / 1e4;

describe('deltaE2000Lab', () => {
  it.each(SHARMA)('matches Sharma et al. for %j vs %j', (a, b, expected) => {
    expect(round4(deltaE2000Lab(a, b))).toBe(expected);
    expect(round4(deltaE2000Lab(b, a))).toBe(expected);
  });
});

describe('hexToLab', () => {
  it.each([
    ['#ffffff', [100, 0, 0]],
    ['#000000', [0, 0, 0]],
    ['#ff0000', [53.2408, 80.0925, 67.2032]],
    ['#0000ff', [32.297, 79.1875, -107.8602]],
    ['#808080', [53.585, 0, 0]],
  ] as const)('converts %s to CIE L*a*b* (D65)', (hex, [l, a, b]) => {
    const [L, A, B] = hexToLab(hex);
    expect(L).toBeCloseTo(l, 2);
    expect(A).toBeCloseTo(a, 2);
    expect(B).toBeCloseTo(b, 2);
  });

  it('rejects anything but six-digit hex', () => {
    expect(() => hexToLab('rgb(0, 0, 0)')).toThrow(/hex/);
  });
});

describe('deltaE2000', () => {
  it('compares hex colours through L*a*b*', () => {
    expect(deltaE2000('#000000', '#ffffff')).toBeCloseTo(100, 4);
    expect(deltaE2000('#3b82f6', '#3b82f6')).toBe(0);
    expect(deltaE2000('#3b82f6', '#3B82F6')).toBe(0);
  });
});
